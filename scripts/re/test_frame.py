def calc_crc8(data: bytes) -> int:
    crc = 0
    for b in data:
        crc = CRC8_TABLE[crc ^ b]
    return crc

def make_group_frame(group_idx=0, mode=0, decimal_power=100, lamp_level=0, sound=0, lamp_mode=0, auto_num=0):
    # group_idx: 0=A, 1=B, 2=C, 3=D, 4=E
    # mode: 0=M, 1=TTL, 2=Multi, 3=OFF
    # decimal_power: 100 for 1/1, 90 for 1/2, ..., 30 for 1/128
    # power_byte = 100 - decimal_power
    power_byte = (100 - decimal_power) & 0xFF
    payload = [
        0xF0,          # header
        0xA1,          # cmd
        0x07,          # len
        group_idx,     # group
        mode,          # mode
        power_byte,    # power
        lamp_level,    # lamp level
        sound,         # sound
        lamp_mode,     # lamp mode
        auto_num,      # auto power
    ]
    crc = calc_crc8(bytes(payload))
    payload.append(crc)
    return bytes(payload)

